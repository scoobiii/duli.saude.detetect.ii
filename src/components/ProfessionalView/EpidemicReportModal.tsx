import React, { useState } from 'react';
import {
  FileText,
  X,
  Sparkles,
  Bot,
  Printer,
  ShieldAlert,
  Users,
  CheckCircle2,
  AlertTriangle,
  Download,
} from 'lucide-react';
import { EpidemiologicalReport, NeighborhoodCluster, AppLanguage, AIEngineMode } from '../../types';
import { generateLocalEpidemicReport } from '../../services/localAgent';
import { requestGeminiEpidemicReport } from '../../services/geminiService';

interface ReportModalProps {
  isOpen: boolean;
  onClose: () => void;
  clusters: NeighborhoodCluster[];
  engineMode: AIEngineMode;
  language: AppLanguage;
}

export const EpidemicReportModal: React.FC<ReportModalProps> = ({
  isOpen,
  onClose,
  clusters,
  engineMode,
  language,
}) => {
  const pt = language === 'pt';

  const [isLoading, setIsLoading] = useState<boolean>(false);
  const [report, setReport] = useState<EpidemiologicalReport | null>(null);
  const [errorMsg, setErrorMsg] = useState<string | null>(null);

  if (!isOpen) return null;

  const handleGenerate = async () => {
    setIsLoading(true);
    setErrorMsg(null);

    try {
      if (engineMode === 'gemini_flash') {
        try {
          const res = await requestGeminiEpidemicReport(clusters, language);
          setReport(res);
        } catch (apiErr: any) {
          console.warn('Gemini report failed, falling back to local heuristic report:', apiErr);
          const fallback = generateLocalEpidemicReport(clusters, language);
          setReport(fallback);
          setErrorMsg(
            pt
              ? 'Nota: Gerado pelo Agente Heurístico Local devido à indisponibilidade momentânea da chave Gemini.'
              : 'Note: Generated by Local Heuristic Agent as Gemini API could not be reached.'
          );
        }
      } else {
        const res = generateLocalEpidemicReport(clusters, language);
        setReport(res);
      }
    } catch (e: any) {
      setErrorMsg(e.message || 'Erro ao gerar boletim.');
    } finally {
      setIsLoading(false);
    }
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 bg-slate-950/70 backdrop-blur-xs flex items-center justify-center p-4">
      <div className="bg-white rounded-3xl max-w-3xl w-full p-6 sm:p-8 shadow-2xl border border-slate-200 max-h-[90vh] overflow-y-auto space-y-6 animate-fade-in">
        {/* Header */}
        <div className="flex items-center justify-between pb-4 border-b border-slate-200">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-teal-100 text-teal-700 flex items-center justify-center">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-xl font-black text-slate-900">
                {pt ? 'Boletim Epidemiológico Comunitário' : 'Community Epidemiological Bulletin'}
              </h3>
              <p className="text-xs text-slate-500">
                {pt
                  ? 'Geração automática de inteligência estratégica para ACS e Gestores de Saúde'
                  : 'Automated strategic intelligence for health agents and clinic managers'}
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="p-2 rounded-xl text-slate-400 hover:text-slate-700 hover:bg-slate-100"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {errorMsg && (
          <div className="p-3 bg-amber-50 border border-amber-200 text-amber-800 rounded-xl text-xs flex items-center gap-2">
            <AlertTriangle className="w-4 h-4 text-amber-600 shrink-0" />
            <span>{errorMsg}</span>
          </div>
        )}

        {/* Not yet generated */}
        {!report ? (
          <div className="text-center py-8 space-y-4">
            <div className="w-16 h-16 rounded-2xl bg-teal-50 text-teal-600 flex items-center justify-center mx-auto">
              <FileText className="w-8 h-8" />
            </div>
            <div>
              <h4 className="text-lg font-bold text-slate-800">
                {pt ? 'Pronto para Consolidar os Dados de Vigilância' : 'Ready to Consolidate Surveillance Data'}
              </h4>
              <p className="text-xs text-slate-500 max-w-md mx-auto mt-1">
                {pt
                  ? 'O sistema irá analisar todos os bairros monitorados, calcular o R(t) efetivo e gerar recomendações de campo imediatas para os Agentes Comunitários.'
                  : 'The engine will analyze all monitored micro-sectors, compute the transmission R(t), and formulate concrete field directives for health agents.'}
              </p>
            </div>

            <button
              onClick={handleGenerate}
              disabled={isLoading}
              className={`flex items-center gap-2 px-6 py-3.5 rounded-2xl text-white font-bold text-sm shadow-md transition-all mx-auto ${
                isLoading
                  ? 'bg-slate-600 cursor-wait'
                  : 'bg-teal-600 hover:bg-teal-500 active:scale-95'
              }`}
            >
              {isLoading ? (
                <>
                  <div className="w-4 h-4 border-2 border-white border-t-transparent rounded-full animate-spin" />
                  <span>{pt ? 'Sintetizando Dados...' : 'Synthesizing Telemetry...'}</span>
                </>
              ) : engineMode === 'gemini_flash' ? (
                <>
                  <Sparkles className="w-4 h-4 text-amber-300" />
                  <span>{pt ? 'Gerar Boletim com Gemini 3.8 Flash' : 'Generate Bulletin with Gemini 3.8'}</span>
                </>
              ) : (
                <>
                  <Bot className="w-4 h-4 text-blue-200" />
                  <span>{pt ? 'Gerar Boletim com Agente Local (Offline)' : 'Generate Bulletin with Local Agent'}</span>
                </>
              )}
            </button>
          </div>
        ) : (
          /* Report View */
          <div className="space-y-5 print:p-0">
            {/* Top Badge */}
            <div className="p-4 bg-slate-900 text-white rounded-2xl flex flex-wrap items-center justify-between gap-4">
              <div>
                <span className="text-[10px] text-teal-400 font-mono block">
                  FASE EPIDÊMICA IDENTIFICADA
                </span>
                <span className="text-lg font-black text-white">{report.epidemicPhase}</span>
              </div>
              <div className="flex items-center gap-4">
                <div className="text-right">
                  <span className="text-[10px] text-slate-400 font-mono block">R(t) ESTIMADO</span>
                  <span className="text-lg font-black font-mono text-amber-300">
                    {report.estimatedRt.toFixed(2)}
                  </span>
                </div>
                <div className="text-right">
                  <span className="text-[10px] text-slate-400 font-mono block">NÍVEL DE ALERTA</span>
                  <span className="text-xs font-black px-2.5 py-1 rounded-full bg-rose-600 text-white">
                    {report.alertLevel}
                  </span>
                </div>
              </div>
            </div>

            {/* Executive Summary */}
            <div className="p-5 bg-slate-50 rounded-2xl border border-slate-200">
              <h4 className="text-xs font-bold text-slate-500 uppercase tracking-wider mb-2">
                {pt ? 'Sumário Executivo para a Coordenação' : 'Executive Coordinator Briefing'}
              </h4>
              <p className="text-sm font-medium text-slate-800 leading-relaxed">
                {report.executiveSummary}
              </p>
            </div>

            {/* Priority Actions for ACS */}
            <div className="p-5 bg-teal-50/70 border border-teal-200 rounded-2xl">
              <h4 className="text-xs font-bold text-teal-900 uppercase tracking-wider mb-3 flex items-center gap-1.5">
                <Users className="w-4 h-4 text-teal-700" />
                <span>{pt ? 'Plano de Ação Imediato para os Agentes Comunitários (ACS)' : 'Immediate ACS Field Action Directives'}</span>
              </h4>
              <ul className="space-y-2 text-xs font-semibold text-teal-950">
                {report.priorityActionsForACS.map((act, i) => (
                  <li key={i} className="flex items-start gap-2">
                    <CheckCircle2 className="w-4 h-4 text-teal-600 shrink-0 mt-0.5" />
                    <span>{act}</span>
                  </li>
                ))}
              </ul>
            </div>

            {/* Health System Advice */}
            <div className="p-4 bg-amber-50 border border-amber-200 rounded-2xl text-xs space-y-1">
              <span className="font-bold text-amber-900 block">
                {pt ? 'Diretriz para a Rede de Urgência & Leitos:' : 'Clinical Surge & Bed Capacity Guidance:'}
              </span>
              <p className="text-amber-800 leading-relaxed">{report.healthSystemLoadAdvice}</p>
            </div>

            {/* Print & Close */}
            <div className="flex items-center justify-between pt-4 border-t border-slate-200">
              <span className="text-[11px] text-slate-400 font-mono">
                Gerado por: {report.generatedBy} • {new Date(report.generatedAt).toLocaleDateString()}
              </span>

              <div className="flex items-center gap-2">
                <button
                  onClick={handlePrint}
                  className="flex items-center gap-1.5 px-4 py-2 rounded-xl text-xs font-bold bg-slate-100 hover:bg-slate-200 text-slate-700 transition-colors"
                >
                  <Printer className="w-4 h-4" />
                  <span>{pt ? 'Imprimir / Salvar PDF' : 'Print / PDF'}</span>
                </button>
                <button
                  onClick={onClose}
                  className="px-5 py-2 rounded-xl text-xs font-bold bg-slate-900 hover:bg-slate-800 text-white transition-colors"
                >
                  {pt ? 'Concluir' : 'Done'}
                </button>
              </div>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
